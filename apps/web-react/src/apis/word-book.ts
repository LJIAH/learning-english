const TAG_KEYS = [
  "gk",
  "zk",
  "gre",
  "toefl",
  "ielts",
  "cet6",
  "cet4",
  "ky",
] as const;

export async function getWordBookList(
  params: WordQuery,
): Promise<{ success: boolean; data: WordList }> {
  // 模拟网络往返，便于观察骨架屏
  await new Promise((resolve) => setTimeout(resolve, 400));

  const keyword = params.word?.trim().toLowerCase() ?? "";
  const activeTags = TAG_KEYS.filter((k) => params[k]);

  const filtered = WORDS.filter((w) => {
    if (keyword && !w.word.toLowerCase().includes(keyword)) return false;
    // 标签为「或」关系，与后端约定一致
    if (activeTags.length > 0 && !activeTags.some((k) => w[k])) return false;
    return true;
  });

  const start = (params.page - 1) * params.pageSize;
  const list = filtered.slice(start, start + params.pageSize);

  return { success: true, data: { list, total: filtered.length } };
}
